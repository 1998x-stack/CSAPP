#!/usr/bin/env python3
"""Build a complete, evidence-based, non-destructive CSAPP documentation view.

All 380 numbered entries get a local page, regardless of file coverage.
Original learning notes are read from their existing locations (never edited).
Explicit --generate writes solely to build/m05-docs, protected by a marker.
"""
from __future__ import annotations

import argparse
import ast
from collections import Counter
import json
from pathlib import Path
import re
import shutil
import sys
from urllib.parse import quote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "curriculum/catalog.json"
REVIEWS = ROOT / "curriculum/reviews.json"
OUTPUT = ROOT / "build/m05-docs"
MARKER = ".m05-autogenerated"
REPO_URL = "https://github.com/1998x-stack/CSAPP/blob/main/"
TARGET_COUNT = 380
M02_TEST_FILE = ROOT / "tests/test_m02_examples.py"
BT = chr(96)

LINK = re.compile(r"(!?\[[^\]]*\]\()([^\s)]+)(\))")
BLOCK_COMMENT = re.compile(r"/\*.*?\*/", re.S)
LINE_COMMENT = re.compile(r"//[^\n]*")
VALID_ID = re.compile(r"^(?:[1-9]|1[0-2])\.\d+(?:\.\d+)?$|^A\.\d+$")


def json_read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def checked_file(relative):
    path = ROOT / relative
    if not path.resolve().is_relative_to(ROOT.resolve()) or path.is_symlink() or not path.is_file():
        raise ValueError(f"Unsafe or missing learning asset: {relative}")
    return path


def get_verified_sources():
    # The M02 suite contains static (relative_file, output_markers) CASES.
    module = ast.parse(M02_TEST_FILE.read_text(encoding="utf-8"))
    for node in module.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "CASES" for t in node.targets
        ):
            cases = ast.literal_eval(node.value)
            return {"02_程序结构和执行/" + source for source, _ in cases}
    raise ValueError("M02 test CASES not found")


def get_reviews(catalog):
    reviews = json_read(REVIEWS)
    if reviews.get("schema_version") != 1:
        raise ValueError("Unsupported review evidence schema")
    entries = {e["id"]: e for e in catalog["entries"]}
    verified_source_paths = get_verified_sources()
    accepted = {}
    for section in ("notes_reviewed", "code_reviewed", "tests_verified"):
        block = reviews.get(section)
        if not isinstance(block, list):
            raise ValueError(f"Review list absent: {section}")
        seen = set()
        items = {}
        for record in block:
            if not isinstance(record, dict):
                raise ValueError(f"Invalid evidence record: {record}")
            ident = record.get("id")
            evidence = record.get("evidence")
            if ident in seen or ident not in entries or entries[ident]["status"] != "topic_files":
                raise ValueError(f"Duplicate, missing or non-topic approval: {ident}")
            if not isinstance(evidence, str) or not evidence.startswith("https://github.com/"):
                raise ValueError(f"Review evidence must link a GitHub review: {ident}")
            seen.add(ident)
            if section == "tests_verified":
                source = record.get("source")
                if (record.get("suite") != "tests/test_m02_examples.py"
                    or source not in verified_source_paths
                    or source != entries[ident]["topic_base"] + ".cpp"):
                    raise ValueError(f"Verified test evidence is not linked to the M02 suite: {ident}")
            items[ident] = record
        accepted[section] = items
    return accepted


def substantive_note(raw):
    kept = []
    for line in raw.splitlines():
        trimmed = line.strip()
        if (not trimmed or trimmed in ('"""', "'''")
            or trimmed.startswith(("# ", "Lecture:", "Content:", "<!--", "-->"))):
            continue
        kept.append(trimmed)
    # The threshold classifies a drafted note, never certifies its quality.
    return len("".join(kept)) >= 80


def substantive_cpp(raw):
    without_comments = LINE_COMMENT.sub("", BLOCK_COMMENT.sub("", raw))
    return bool(without_comments.strip())


def substantive_python(raw):
    try:
        statements = ast.parse(raw).body
    except SyntaxError:
        return True  # Broken code is still non-template, never verified.
    if not statements:
        return False
    return not (len(statements) == 1 and isinstance(statements[0], ast.Expr)
                and isinstance(statements[0].value, ast.Constant)
                and isinstance(statements[0].value.value, str))


def source_link(relative):
    return REPO_URL + quote(relative, safe="/")


def rewrite_links(content, relative):
    base = checked_file(relative).parent
    def replace(match):
        target = match.group(2)
        if target.startswith(("https:", "http:", "mailto:", "#", "data:", "//", "/")):
            return match.group(0)
        url = urlsplit(target)
        try:
            candidate = (base / url.path).resolve()
        except (OSError, ValueError):
            return match.group(0)
        if not candidate.is_relative_to(ROOT.resolve()) or not candidate.is_file():
            return match.group(0)
        rel = candidate.relative_to(ROOT).as_posix()
        href = source_link(rel)
        if url.query:
            href += "?" + url.query
        if url.fragment:
            href += "#" + url.fragment
        return match.group(1) + href + match.group(3)
    return LINK.sub(replace, content)


def classify(entry, reviews):
    status = entry["status"]
    result = {
        "id": entry["id"], "chapter_id": entry["chapter_id"],
        "title_zh": entry["title_zh"], "mapping": status,
        "notes": "not_applicable", "code": "not_applicable",
        "test": "not_registered",
    }
    if status != "topic_files":
        return result
    base = entry["topic_base"]
    md = checked_file(base + ".md").read_text(encoding="utf-8")
    cpp = checked_file(base + ".cpp").read_text(encoding="utf-8")
    py = checked_file(base + ".py").read_text(encoding="utf-8")
    has_notes = substantive_note(md)
    has_code = substantive_cpp(cpp) or substantive_python(py)
    result["notes"] = (
        "reviewed" if entry["id"] in reviews["notes_reviewed"]
        else "draft" if has_notes else "template"
    )
    result["code"] = (
        "reviewed" if entry["id"] in reviews["code_reviewed"]
        else "implemented" if has_code else "template"
    )
    if result["notes"] == "reviewed" and not has_notes:
        raise ValueError(f"Cannot approve an empty note: {entry['id']}")
    if result["code"] == "reviewed" and not has_code:
        raise ValueError(f"Cannot approve an empty code example: {entry['id']}")
    verified = entry["id"] in reviews["tests_verified"]
    if verified:
        if not substantive_cpp(cpp):
            raise ValueError(f"Verified test has no C++ implementation: {entry['id']}")
        result["test"] = "verified"
        result["test_evidence"] = reviews["tests_verified"][entry["id"]]["evidence"]
    elif base + ".cpp" in get_verified_sources():
        result["test"] = "registered"
    result["source_links"] = {ext.lstrip("."): source_link(base + ext) for ext in entry["file_extensions"]}
    return result


def location(entry):
    if entry["chapter_id"] == "A":
        return f"appendix/{entry['id']}.md"
    return f"chapters/{int(entry['chapter_id']):02d}/{entry['id']}.md"


def reference_link(entry, origin):
    target = location(entry)
    if origin == "chapters/index.md":
        return "../" + target
    if origin in ("index.md", "progress.md"):
        return target
    if origin == "appendix/index.md" and entry["chapter_id"] == "A":
        return entry["id"] + ".md"
    return entry["id"] + ".md"


def make_entry_page(entry, state, chapter_entries):
    heading = f"# {entry['id']} {entry['title_zh']}"
    body = [heading, "", f"**教材目录映射：{state['mapping']}**", ""]
    if entry["status"] == "unmapped":
        body.extend([
            "**待完善：原书目录中存在本条目，但当前仓库没有对应原始知识文件。**",
            "",
            "本页仅提供导航占位，不包含编造的教材讲解或实验结论。",
        ])
    elif entry["status"] == "section_directory":
        body.extend(["本条目是包含下级知识点的父节目录，并非遗漏，也不能视作独立文章已完成。", "", "## 下级条目", ""])
        children = [e for e in chapter_entries if e["id"].startswith(entry["id"] + ".")
                    and e["id"].count(".") == entry["id"].count(".") + 1]
        body.extend(f"- [{e['id']} {e['title_zh']}]({e['id']}.md)" for e in children)
        if not children:
            raise ValueError(f"Parent section has no children: {entry['id']}")
    else:
        body.extend([
            f"**讲解：{state['notes']}　代码：{state['code']}　测试：{state['test']}**",
            "",
            "说明：draft 仅说明已有讲解文字；implemented 仅说明有代码，均不自动代表质量已审核。",
            "",
            "原始文件：" + " | ".join(f"[{name}]({href})" for name, href in state["source_links"].items()),
            "",
        ])
        if state["test"] == "verified":
            body.extend([f"验证依据：[M02 已通过的测试 PR]({state['test_evidence']})", ""])
        if state["notes"] != "template":
            source = entry["topic_base"] + ".md"
            original = checked_file(source).read_text(encoding="utf-8")
            body.extend(["## 原始学习笔记", "", rewrite_links(original, source)])
        else:
            body.extend(["## 学习笔记待完善", "", "原 Markdown 仅包含初始模板，当前没有经过审核的知识讲解。"])
    body.extend(["", f"[返回本章导航]({'index.md'})", ""])
    return "\n".join(body)


def build_plan():
    catalog = json_read(CATALOG)
    entries = catalog.get("entries", [])
    if len(entries) != TARGET_COUNT or len({e["id"] for e in entries}) != TARGET_COUNT:
        raise ValueError("M05 requires 380 distinct M04 catalog entries")
    if catalog.get("totals", {}).get("chapters") != 12:
        raise ValueError("M05 requires all 12 chapters")
    if set(e["status"] for e in entries) != {"topic_files", "section_directory", "unmapped"}:
        raise ValueError("Unexpected M04 mapping categories")
    if any(not VALID_ID.fullmatch(e["id"]) or not e.get("title_zh") for e in entries):
        raise ValueError("Invalid or untitled catalog entry")
    reviews = get_reviews(catalog)
    states = [classify(entry, reviews) for entry in entries]
    by_id = {s["id"]: s for s in states}
    plans = {}
    counters = Counter()
    for state in states:
        for attr in ("mapping", "notes", "code", "test"):
            counters[attr + ":" + state[attr]] += 1
    groups = {str(i): [entry for entry in entries if entry["chapter_id"] == str(i)] for i in range(1, 13)}
    groups["A"] = [entry for entry in entries if entry["chapter_id"] == "A"]
    if any(not groups[str(i)] for i in range(1, 13)) or len(groups["A"]) != 2:
        raise ValueError("Missing chapter or appendix coverage")
    for entry, state in zip(entries, states):
        path = location(entry)
        if path in plans:
            raise ValueError(f"Duplicate documentation page: {path}")
        plans[path] = make_entry_page(entry, state, groups[entry["chapter_id"]])

    chapter_titles = {item["id"]: item["title_zh"] for item in catalog["chapters"]}
    overview = ["# CSAPP 全量学习导航", "",
                "目录完整性基于 CSAPP 第三版 Global Edition 的 12 章与附录 A。", "",
                "每一个编号都有独立网页；未映射和未审定内容明确标注。", "",
                "## 章节入口", ""]
    chapter_root = ["# 教材章节索引", "", "12 章与附录均在此列出。", ""]
    for i in range(1, 13):
        label = f"{i:02d} {chapter_titles[str(i)]}"
        overview.append(f"- [{label}](chapters/{i:02d}/index.md)")
        chapter_root.append(f"- [{label}]({i:02d}/index.md)")
        nav = [f"# 第 {i} 章：{chapter_titles[str(i)]}", "",
               f"本章有 {len(groups[str(i)])} 个带编号条目。文件存在不意味着知识内容完成。", ""]
        for entry in groups[str(i)]:
            state = by_id[entry["id"]]
            nav.append(f"- [{entry['id']} {entry['title_zh']}]({entry['id']}.md) — {state['mapping']}; {state['notes']}; {state['code']}; {state['test']}")
        plans[f"chapters/{i:02d}/index.md"] = "\n".join(nav) + "\n"
    overview += ["- [附录 A](appendix/index.md)", "", "[全量内容进度统计](progress.md)", ""]
    chapter_root += ["- [附录 A](../appendix/index.md)", ""]
    plans["index.md"] = "\n".join(overview)
    plans["chapters/index.md"] = "\n".join(chapter_root)
    plans["appendix/index.md"] = "\n".join(
        ["# 附录 A：错误处理", ""] +
        [f"- [{e['id']} {e['title_zh']}]({e['id']}.md)" for e in groups["A"]] + [""])
    rows = ["# 内容与审核进度", "",
            "以下状态按单一来源代码和明确审核证据生成，不以文件数代替完成度。", "",
            "| 维度 | 分类 | 数量 |", "| --- | --- | ---: |"]
    rows.extend(f"| {k.split(':', 1)[0]} | {k.split(':', 1)[1]} | {v} |"
                for k, v in sorted(counters.items()))
    rows += ["", "## 状态定义", "",
             "- notes: template 仅模板；draft 有实质文字但未审核；reviewed 经带证据的人工审核。",
             "- code: template 仅模板；implemented 有代码但不证明正确；reviewed 经审核。",
             "- test: not_registered 未登记；registered 已加入自动测试；verified 有明确的已通过 CI/PR 证据。",
             "- mapping: topic_files 原文件组；section_directory 父节目录；unmapped 教材编号存在但仓库缺失。",
             "", "报告还覆盖附录 A 和四份不属于标准知识点文件组的补充资料。",
             "", "## 补充资料", ""]
    rows += [f"- [{supp['path']}]({source_link(supp['path'])})"
             for supp in catalog["supplementary_files"]]
    plans["progress.md"] = "\n".join(rows) + "\n"
    plans["metadata/status.json"] = json.dumps({
        "schema_version": 1,
        "entry_count": len(entries),
        "counts": dict(sorted(counters.items())),
        "entries": states,
        "supplementary_files": catalog["supplementary_files"],
    }, ensure_ascii=False, indent=2) + "\n"
    return plans


def generate(plans, output):
    output = output.resolve()
    allowed = OUTPUT.resolve()
    if output != allowed:
        raise ValueError(f"Generation is permitted only under {allowed}")
    if output.exists():
        if not (output / MARKER).is_file():
            raise ValueError("Refusing to replace unmarked documentation directory")
        if output.is_symlink():
            raise ValueError("Refusing to follow a symlinked documentation directory")
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / MARKER).write_text("Generated by scripts/build_docs.py; safe to recreate.\n", encoding="utf-8")
    for name, text in plans.items():
        path = output / name
        if not path.resolve().is_relative_to(output):
            raise ValueError(f"Unsafe generated page: {name}")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--generate", action="store_true", help="Generate complete pages in build/m05-docs")
    group.add_argument("--verify-generated", action="store_true", help="Verify every page equals generated source")
    args = parser.parse_args()
    plans = build_plan()
    counts = {"numbered_pages": TARGET_COUNT, "generated_files": len(plans)}
    if args.generate:
        generate(plans, OUTPUT)
    if args.verify_generated:
        for name, content in plans.items():
            path = OUTPUT / name
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                raise ValueError(f"Generated page missing or stale: {name}")
        actual = {p.relative_to(OUTPUT).as_posix() for p in OUTPUT.rglob("*") if p.is_file()}
        if actual - set(plans) != {MARKER}:
            raise ValueError(f"Unexpected generated files: {sorted(actual - set(plans))}")
    print(json.dumps(counts, ensure_ascii=False))


if __name__ == "__main__":
    sys.exit(main())
